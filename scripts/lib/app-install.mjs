/**
 * Where "←" of the installed app leads: back in the history when the visitor came from a page of the site,
 * otherwise the start page (the app opened right on this page, e.g. from a shortcut). Null on the start page (no "←").
 */
export function backTarget({ pathname, referrer, origin, base = '/' }) {
  if (pathname === base || pathname === base.replace(/\/$/, '')) return null;
  return referrer && referrer.startsWith(`${origin}${base}`) ? 'history' : base;
}

/** localStorage key: the day (YYYY-MM-DD) Detail dne was last stored for offline (once a day is enough). */
