/** Local day of `date` as YYYY-MM-DD, and the one `add` days later (the days of the game change at local midnight). */
export function isoDay(date, add = 0) {
  const d = new Date(date.getFullYear(), date.getMonth(), date.getDate() + add);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * Pictures Detail dne needs on the `dates` (YYYY-MM-DD) from its data (/detail-dne/data.json): for every level of a
 * planned day the close-up's work in its largest width and every offered work (the answer too) in its smallest, as the
 * game asks for them (`picture` in src/lib/detail-game.ts: <base><folder>/<width>.webp). Unknown works are skipped.
 */
export function gameOfflineFiles(data, dates, base = '/') {
  const byId = new Map((data?.works ?? []).map((w) => [w.id, w]));
  const want = new Set(dates);
  const files = new Set();
  const file = (w, largest) => `${base}${w.folder}/${largest ? Math.max(...w.widths) : Math.min(...w.widths)}.webp`;
  for (const day of Object.values(data?.plan?.days ?? {})) {
    if (!want.has(day?.date)) continue;
    for (const puzzle of Object.values(day)) {
      if (!puzzle || typeof puzzle !== 'object' || !puzzle.targetId) continue;
      const target = byId.get(puzzle.targetId);
      if (target) files.add(file(target, true));
      for (const id of puzzle.optionIds ?? []) {
        const w = byId.get(id);
        if (w) files.add(file(w, false));
      }
    }
  }
  return [...files];
}

/**
 * Build files (/_astro/…) a page or a script refers to, as absolute URLs: the scripts and styles of a page (`src` /
 * `href` in its HTML) and the modules a script (`from` ending with .js) imports (`from "./x.js"`, `import("./x.js")`),
 * so a page never opened works offline. Markup inside a script (`src="${…}"` of a template) is not a file.
 */
export function buildAssets(text, from, base = '/') {
  const found = new Set();
  const astro = `${base}_astro/`;
  const script = new URL(from).pathname.endsWith('.js');
  const pattern = script ? /(?:\bfrom|\bimport)\s*\(?\s*["']([^"'$]+\.js)["']/g : /(?:src|href)=["']([^"'$]+)["']/g;
  for (const [, ref] of text.matchAll(pattern)) {
    const url = new URL(ref, from);
    url.hash = '';
    if (url.origin === new URL(from).origin && url.pathname.startsWith(astro)) found.add(url.href);
  }
  return [...found];
}
