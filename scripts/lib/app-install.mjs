// The site as an app on a phone (or a computer): installing it, opening it from the home screen and using it offline.
//
// - The service worker /sw.js (src/pages/sw.js.ts, text from swScript) caches what a visitor has seen: pages network
//   first (fresh when online, the last copy offline, else the page OFFLINE_PATH), the hashed files of the build
//   (/_astro/) cache first, pictures and fonts stale-while-revalidate (at once from the cache, refreshed behind).
//   Every build has its own version, so a deploy drops the old pages and files; pictures stay (APP_CACHES.images,
//   at most IMAGE_CACHE_LIMIT, the oldest go first).
// - Installing: installMode says what the footer button "Nainstalovat" does (src/lib/app-install.ts):
//   the browser's own prompt (Android, Chrome, Edge), a short how-to for iPhone/iPad (Share → Add to Home Screen)
//   or for another phone browser (its menu), nothing on a computer without a prompt or inside the installed app.
// - Inside the installed app (display-mode standalone) the header has "←" (iPhone has no Back of its own there).

/** Address of the service worker and of the page shown offline, relative to the base of the site. */
export const SW_FILE = 'sw.js';
export const OFFLINE_PATH = 'offline/';

/** Caches of the service worker; the prefix marks ours, so an update deletes only our old ones. */
export const CACHE_PREFIX = 'pavla-';
/** Most pictures kept for offline (the oldest are deleted first); a picture is some 50–300 kB. */
export const IMAGE_CACHE_LIMIT = 400;
/** Most pages kept for offline (one per address without its query: the filters are read by the page itself). */
export const PAGE_CACHE_LIMIT = 150;

/** Names of the caches of a build `version`: pages and build files per build, pictures and fonts across builds. */
export function appCaches(version) {
  const v = String(version).replace(/[^\w.-]/g, '');
  if (!v) throw new Error('the service worker needs a version');
  return {
    pages: `${CACHE_PREFIX}pages-${v}`,
    files: `${CACHE_PREFIX}files-${v}`,
    images: `${CACHE_PREFIX}images`,
    fonts: `${CACHE_PREFIX}fonts`,
  };
}

/**
 * How the service worker answers a request: `pass` (not at all, the browser alone), `network` (network first, the
 * cache when offline; `cache` = which one), `cache` (cache first: files that never change under their name) or
 * `swr` (stale-while-revalidate). `url` = URL, `mode` = request.mode, `base` = base path of the site ("/").
 * Self-contained (no imports, no constants of the module): swScript copies it into /sw.js as text.
 */
export function requestStrategy(url, method, mode, origin, base) {
  if (method !== 'GET') return { how: 'pass' };
  if (url.origin === 'https://fonts.googleapis.com') return { how: 'swr', cache: 'fonts' };
  if (url.origin === 'https://fonts.gstatic.com') return { how: 'cache', cache: 'fonts' };
  if (url.origin !== origin) return { how: 'pass' };
  const path = url.pathname;
  if (!path.startsWith(base) || path === `${base}sw.js`) return { how: 'pass' };
  if (mode === 'navigate') return { how: 'network', cache: 'pages', page: true };
  if (path.startsWith(`${base}_astro/`)) return { how: 'cache', cache: 'files' };
  if (/\.(avif|webp|jpe?g|png|gif|svg|ico)$/i.test(path)) return { how: 'swr', cache: 'images' };
  return { how: 'network', cache: 'pages', page: false };
}

/** Cache key of a page: its address without the query and hash (/tvorba/?tag=voda and /tvorba/ are one page). */
export function pageKey(url) {
  return `${url.origin}${url.pathname}`;
}

/**
 * Files stored at install, so the start page, the offline page and the icons work offline from the first visit; in
 * the cache of the build files, which has no limit (the page cache drops its oldest entries).
 */
export function precacheFiles(base) {
  return [base, `${base}${OFFLINE_PATH}`, `${base}site.webmanifest`, `${base}favicon.svg`, `${base}icon-192.png`];
}

/** Source of /sw.js for the build `version` and the base path of the site. */
export function swScript(version, base = '/') {
  const caches = appCaches(version);
  return `// Service worker of the site, build ${version} (generated by scripts/lib/app-install.mjs, do not edit).
const CACHES = ${JSON.stringify(caches)};
const BASE = ${JSON.stringify(base)};
const OFFLINE = BASE + ${JSON.stringify(OFFLINE_PATH)};
const PRECACHE = ${JSON.stringify(precacheFiles(base))};
const LIMITS = { [CACHES.images]: ${IMAGE_CACHE_LIMIT}, [CACHES.pages]: ${PAGE_CACHE_LIMIT} };
const requestStrategy = ${requestStrategy.toString()};
const pageKey = ${pageKey.toString()};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHES.files).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

// A new build: delete our caches of older builds (pictures and fonts stay), then serve the open pages at once.
self.addEventListener('activate', (event) => {
  const keep = new Set(Object.values(CACHES));
  event.waitUntil(caches.keys()
    .then((names) => Promise.all(names.filter((n) => n.startsWith(${JSON.stringify(CACHE_PREFIX)}) && !keep.has(n)).map((n) => caches.delete(n))))
    .then(() => self.clients.claim()));
});

async function store(name, key, response) {
  if (!response || !response.ok || (response.type !== 'basic' && response.type !== 'cors')) return;
  const cache = await caches.open(name);
  await cache.put(key, response);
  const limit = LIMITS[name];
  if (!limit) return;
  const keys = await cache.keys();
  for (const old of keys.slice(0, Math.max(0, keys.length - limit))) await cache.delete(old);
}

async function networkFirst(event, name, key, page) {
  try {
    const response = await fetch(event.request);
    event.waitUntil(store(name, key, response.clone()));
    return response;
  } catch (error) {
    // Its own cache first (the latest copy), then any (the start page stored at install).
    const cached = (await (await caches.open(name)).match(key)) || (await caches.match(key));
    if (cached) return cached;
    if (page) return (await caches.match(OFFLINE)) || Response.error();
    throw error;
  }
}

async function cacheFirst(event, name) {
  const cached = await caches.match(event.request);
  if (cached) return cached;
  const response = await fetch(event.request);
  event.waitUntil(store(name, event.request, response.clone()));
  return response;
}

async function staleWhileRevalidate(event, name) {
  const cached = await caches.match(event.request);
  const fresh = fetch(event.request).then(async (response) => { await store(name, event.request, response.clone()); return response; });
  if (cached) {
    event.waitUntil(fresh.catch(() => null));
    return cached;
  }
  return fresh;
}

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  const s = requestStrategy(url, event.request.method, event.request.mode, self.location.origin, BASE);
  if (s.how === 'pass') return;
  const name = CACHES[s.cache];
  if (s.how === 'network') event.respondWith(networkFirst(event, name, s.page ? pageKey(url) : event.request, s.page));
  else if (s.how === 'cache') event.respondWith(cacheFirst(event, name));
  else event.respondWith(staleWhileRevalidate(event, name));
});
`;
}

/**
 * What "Nainstalovat" does (`hidden` = no button): `prompt` = the browser's own install dialog
 * (beforeinstallprompt: Android, Chrome, Edge), `ios` = how-to for iPhone and iPad (no prompt there, every browser
 * installs through Share), `menu` = how-to for another phone browser (Firefox, Samsung: their menu), hidden inside the
 * installed app and on a computer without a prompt (nothing to offer there).
 */
export function installMode({ standalone, prompt, ios, phone }) {
  if (standalone) return 'hidden';
  if (prompt) return 'prompt';
  if (ios) return 'ios';
  if (phone) return 'menu';
  return 'hidden';
}

/** iPhone or iPad from the user agent (iPadOS says Macintosh, but has a touch screen). */
export function isIos(userAgent, maxTouchPoints = 0) {
  return /iPhone|iPad|iPod/.test(userAgent) || (/Macintosh/.test(userAgent) && maxTouchPoints > 1);
}

