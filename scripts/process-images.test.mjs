const siteConfig = YAML.parse(await fs.readFile(new URL('../site.config.yaml', import.meta.url), 'utf8'));
// Small web widths keep the test fast.
const config = {
  ...siteConfig,
  images: {
    ...siteConfig.images,
    web: { widths: [40, 80], quality: 70 },
    mockups: { widths: [60] },
    details: { widths: [30] },
    photos: { widths: [40] },
    fler: { ...siteConfig.images.fler, longEdge: 120 },
  },
};

let tmp, contentDir, siteDir;
const exists = (p) => fs.access(p).then(() => true, () => false);
const quiet = () => {};
const opts = (over = {}) => ({ contentDir, siteDir, config, log: quiet, ...over });

async function addWork(year, slug, yaml, { image = true } = {}) {
  const dir = path.join(contentDir, 'tvorba', year);
  await fs.mkdir(dir, { recursive: true });
  if (yaml !== undefined) await fs.writeFile(path.join(dir, `${slug}.yaml`), yaml);
  if (image) {
    await sharp({ create: { width: 64, height: 48, channels: 3, background: '#88aacc' } }).jpeg().toFile(path.join(dir, `${slug}.jpg`));
  }
}
const idOf = async (year, slug) => YAML.parse(await fs.readFile(path.join(contentDir, 'tvorba', year, `${slug}.yaml`), 'utf8')).id;

beforeEach(async () => {
  tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'pavla-pipeline-'));
  contentDir = path.join(tmp, 'pavla-content');
  siteDir = path.join(tmp, 'pavla');
  await fs.mkdir(path.join(contentDir, 'tvorba'), { recursive: true });
  await fs.mkdir(siteDir);
});
afterEach(() => fs.rm(tmp, { recursive: true, force: true }));

test('generates web images, metadata copy and exports under <year>/<slug>-<id>', async () => {
  await addWork('2026', 'rano', 'title: Ráno\ndate: 2026-06-14\ninstagram: true\nstatus: available\nprice: 1000\nsize_cm: [40, 30]\n');
  const r = await run(opts());
  assert.equal(r.ok, true);
  assert.equal(r.processed, 1);
  const key = `rano-${await idOf('2026', 'rano')}`;

  const info = JSON.parse(await fs.readFile(path.join(siteDir, 'public/works/2026', key, 'info.json'), 'utf8'));
  // The master is 64 px wide: 40 fits, 80 would upscale, so the full width is added instead.
  assert.deepEqual(info.widths, [40, 64]);
  for (const f of ['40.avif', '40.webp', '40.jpg', '64.jpg']) assert.ok(await exists(path.join(siteDir, 'public/works/2026', key, f)), f);

  const copy = await fs.readFile(path.join(siteDir, 'content/works/2026', `${key}.yaml`), 'utf8');
  assert.match(copy, /^# Generated by/);
  assert.equal(YAML.parse(copy).title, 'Ráno');

  for (const f of [`instagram/2026/${key}-clean.jpg`, `fler/2026/${key}.jpg`, `fler/2026/${key}-mockup-${info.mockups[0].scene}.jpg`]) {
    assert.ok(await exists(path.join(contentDir, 'export', f)), f);
  }
});

